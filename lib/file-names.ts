/**
 * 올라온 파일의 이름을 받는 자리.
 *
 * **macOS 는 한글 파일명을 자모로 분해해 둔다(NFD).** 브라우저는 `File.name` 을 그대로
 * 넘기므로, 맥이나 아이폰에서 올린 `면담녹취_한주케미칼.m4a` 는 우리 DB 에 `ㅎㅏㄴㅈㅜ…`
 * 로 저장된다. 화면에는 똑같이 그려져서 **눈으로는 절대 알아챌 수 없다.**
 *
 * 실제로 그렇게 쌓였다(2026-08-21 실측): 강사 서류 3건 전부와 상담 녹취 1건이 NFD 였고,
 * `file_name like '%한주케미칼%'` 이 0건을 돌려줬다. 사람이 타이핑한 값 153개는 전부
 * 멀쩡했다 — 키보드는 NFC 로 넣기 때문이다. 즉 **깨지는 것은 파일에서 온 이름뿐**이다.
 *
 * 그래서 들어오는 문을 한 곳으로 모은다. 자리마다 normalize 를 흩뿌리면 다음에 업로드
 * 경로가 하나 늘 때 거기만 빠지고, 그 사실은 몇 달 뒤 검색이 안 될 때에야 드러난다.
 */

/** 파일명은 화면에 그대로 보여 주므로 지나치게 길면 잘라 둔다. */
const MAX_FILE_NAME = 300;

export function cleanFileName(value: unknown) {
  if (typeof value !== "string") return "";
  // NFC 로 모아야 사람이 친 글자와 같은 문자열이 된다 — 검색·비교가 그때 비로소 맞는다.
  return value.normalize("NFC").trim().slice(0, MAX_FILE_NAME);
}
